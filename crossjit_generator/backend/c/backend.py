"""Deterministic C11 backend for legal Elementwise candidates."""

from __future__ import annotations

from dataclasses import dataclass
import json
from pathlib import Path
from typing import Any

from crossjit_generator.candidate import Candidate
from crossjit_generator.iteration import (
    IterationDescriptor,
    IterationRankClass,
    OperandAccessKind,
)


class CBackendError(ValueError):
    """The candidate cannot be represented by the C backend."""


@dataclass(frozen=True, slots=True)
class CArtifacts:
    symbol: str
    declaration: str
    header_name: str
    source_name: str
    header: str
    source: str
    manifest: str

    def write(self, directory: Path) -> tuple[Path, Path, Path]:
        directory.mkdir(parents=True, exist_ok=True)
        header_path = directory / self.header_name
        source_path = directory / self.source_name
        manifest_path = directory / f"{self.symbol}.json"
        header_path.write_text(self.header)
        source_path.write_text(self.source)
        manifest_path.write_text(self.manifest)
        return header_path, source_path, manifest_path


@dataclass(frozen=True, slots=True)
class CBundle:
    header: str
    source: str
    metadata: str


def generate_bundle(
    candidates: tuple[Candidate, ...],
    *,
    header_name: str = "generated_crossjit_kernels.h",
) -> CBundle:
    """Combine independently deterministic kernels into one build artifact."""

    backend = CBackend()
    artifacts = sorted(
        (backend.generate(candidate) for candidate in candidates),
        key=lambda item: item.symbol,
    )
    symbols = [artifact.symbol for artifact in artifacts]
    if len(symbols) != len(set(symbols)):
        raise CBackendError("duplicate generated symbol")
    guard = "GENERATED_CROSSJIT_KERNELS_H"
    declarations = []
    definitions = []
    metadata = []
    for artifact in artifacts:
        declarations.append(artifact.declaration)
        lines = artifact.source.splitlines()
        definitions.append("\n".join(lines[3:]).rstrip())
        metadata.append(json.loads(artifact.manifest))
    header = "\n".join((
        "/* Generated by crossjit-generator CBackend v1. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <stddef.h>",
        "",
        *declarations,
        "",
        f"#endif /* {guard} */",
        "",
    ))
    source = "\n\n".join((
        "/* Generated by crossjit-generator CBackend v1. */\n"
        f'#include "{header_name}"',
        *definitions,
    )) + "\n"
    metadata_text = json.dumps({
        "backend": "c",
        "backend_version": backend.VERSION,
        "header": header_name,
        "kernels": metadata,
        "schema_version": 1,
    }, ensure_ascii=True, indent=2, sort_keys=True) + "\n"
    return CBundle(header=header, source=source, metadata=metadata_text)


class CBackend:
    VERSION = "1"
    _OPERATORS = {
        "add": "+",
        "subtract": "-",
        "multiply": "*",
        "true_divide": "/",
    }

    def generate(self, candidate: Candidate) -> CArtifacts:
        if not isinstance(candidate, Candidate):
            raise CBackendError("expected Candidate")
        if candidate.domain != "elementwise":
            raise CBackendError(f"unsupported domain: {candidate.domain}")
        if candidate.lowering_form not in (
                "single_compiler_visible_loop",
                "outer_inner_compiler_visible_loop"):
            raise CBackendError(
                f"unsupported lowering form: {candidate.lowering_form}")
        ir = candidate.elementwise_ir
        if ir.dtype_class not in ("fp64", "float64"):
            raise CBackendError(f"unsupported dtype: {ir.dtype_class}")
        if ir.layout_class not in ("contiguous_same_shape", "inner_contiguous"):
            raise CBackendError(f"unsupported layout: {ir.layout_class}")
        descriptor = candidate.iteration_descriptor
        if descriptor is None:
            scalar_mask = next(
                (int(item.value) for item in ir.specialization_attributes
                 if item.name == "scalar_mask"), 0)
            descriptor = IterationDescriptor.contiguous_same_shape(
                len(ir.inputs), scalar_mask)
        if (len(descriptor.operands) != len(ir.inputs) or
                any(item.access_kind not in (
                    OperandAccessKind.CONTIGUOUS,
                    OperandAccessKind.SCALAR,
                    OperandAccessKind.ZERO_STRIDE,
                ) for item in descriptor.operands)):
            raise CBackendError("unsupported v1 iteration descriptor")

        outer_inner = (
            descriptor.iteration_rank_class is IterationRankClass.OUTER_INNER)
        expected_lowering = (
            "outer_inner_compiler_visible_loop" if outer_inner else
            "single_compiler_visible_loop")
        if candidate.lowering_form != expected_lowering:
            raise CBackendError(
                "lowering form does not match IterationDescriptor")
        if outer_inner and candidate.iteration_descriptor is None:
            raise CBackendError(
                "inner-contiguous lowering requires IterationDescriptor")
        def supported_outer_inner_operand(item):
            if item.access_kind is OperandAccessKind.CONTIGUOUS:
                return (item.inner_stride == "element_size" and
                        item.outer_stride == "runtime_outer_stride" and
                        item.broadcast_relation == "NONE")
            if item.access_kind is OperandAccessKind.SCALAR:
                return (item.inner_stride == 0 and item.outer_stride == 0 and
                        item.broadcast_relation == "SCALAR")
            if item.access_kind is OperandAccessKind.ZERO_STRIDE:
                return (item.inner_stride == 0 and item.outer_stride in (
                            0, "runtime_outer_stride") and
                        item.broadcast_relation != "NONE")
            return False

        if outer_inner and (
                descriptor.outer_shape_class != "AFFINE_ROWS" or
                any(not supported_outer_inner_operand(item)
                    for item in descriptor.operands) or
                descriptor.output.inner_stride != "element_size" or
                descriptor.output.outer_stride !=
                    "runtime_output_outer_stride"):
            raise CBackendError(
                "outer/inner lowering requires affine supported operands")

        signature_hash = candidate.stable_hash()
        prefix = ("crossjit_elem_fp64_inner_contig_" if outer_inner else
                  "crossjit_elem_fp64_contig_")
        symbol = f"{prefix}{signature_hash[:16]}"
        header_name = f"{symbol}.h"
        source_name = f"{symbol}.c"
        guard = f"{symbol.upper()}_H"
        declaration = (
            f"void {symbol}(const void *const *inputs, "
            "const ptrdiff_t *outer_strides, double *restrict output, "
            "size_t outer_count, size_t inner_extent);"
            if outer_inner else
            f"void {symbol}(const void *const *inputs, "
            "double *restrict output, size_t size);"
        )
        header = (
            "/* Generated by crossjit-generator CBackend v1. */\n"
            f"#ifndef {guard}\n"
            f"#define {guard}\n\n"
            "#include <stddef.h>\n\n"
            f"{declaration}\n\n"
            f"#endif /* {guard} */\n"
        )

        value_names = {
            value: f"input_{index}"
            for index, value in enumerate(ir.inputs)
        }
        if outer_inner:
            declarations = []
        else:
            declarations = [
                f"    const double *const input_{index} = "
                f"(const double *)inputs[{index}];"
                for index in range(len(ir.inputs))
            ]
        statements = []
        for index, operation in enumerate(ir.operations):
            expression = operation.semantic_expression
            operator = expression.get("operator")
            c_operator = self._OPERATORS.get(operator)
            if c_operator is None or len(operation.operands) != 2:
                raise CBackendError(
                    f"unsupported atomic expression: {operator}")
            operands = []
            for operand in operation.operands:
                name = value_names.get(operand)
                if name is None:
                    raise CBackendError(
                        f"unknown candidate operand: {operand}")
                if operand in ir.inputs:
                    input_index = ir.inputs.index(operand)
                    access = descriptor.operands[input_index].access_kind
                    operands.append(
                        f"{name}[0]" if access in (
                            OperandAccessKind.SCALAR,
                            OperandAccessKind.ZERO_STRIDE,
                        ) else f"{name}[i]")
                else:
                    operands.append(name)
            result_name = f"value_{index}"
            statements.append(
                f"        const double {result_name} = "
                f"{operands[0]} {c_operator} {operands[1]};")
            value_names[operation.result] = result_name
        output_name = value_names.get(ir.outputs[0])
        if output_name is None:
            raise CBackendError("candidate output is not defined")
        statements.append(f"        output[i] = {output_name};")

        if outer_inner:
            row_declarations = [
                f"        const double *const input_{index} = "
                f"(const double *)((const char *)inputs[{index}] + "
                f"(ptrdiff_t)outer * outer_strides[{index}]);"
                for index in range(len(ir.inputs))
            ]
            source = "\n".join((
                "/* Generated by crossjit-generator CBackend v1. */",
                f'#include "{header_name}"',
                "",
                f"void {symbol}(const void *const *inputs,",
                "            const ptrdiff_t *outer_strides,",
                "            double *restrict output, size_t outer_count,",
                "            size_t inner_extent)",
                "{",
                "    for (size_t outer = 0; outer < outer_count; outer++) {",
                *row_declarations,
                "        double *restrict output_row =",
                "            output + outer * inner_extent;",
                "        for (size_t i = 0; i < inner_extent; i++) {",
                *[line.replace("        output[i]", "            output_row[i]")
                  if "output[i]" in line else "    " + line
                  for line in statements],
                "        }",
                "    }",
                "}",
                "",
            ))
        else:
            source = "\n".join((
                "/* Generated by crossjit-generator CBackend v1. */",
                f'#include "{header_name}"',
                "",
                f"void {symbol}(const void *const *inputs,",
                "            double *restrict output, size_t size)",
                "{",
                *declarations,
                "    for (size_t i = 0; i < size; i++) {",
                *statements,
                "    }",
                "}",
                "",
            ))
        manifest_data: dict[str, Any] = {
            "backend": "c",
            "backend_version": self.VERSION,
            "candidate_hash": signature_hash,
            "dtype_class": ir.dtype_class,
            "error_mode": ir.error_mode,
            "header": header_name,
            "input_count": len(ir.inputs),
            "entry_abi": ("outer_inner_v1" if outer_inner else "flat_v1"),
            "ir_hash": ir.stable_hash(),
            "layout_class": ir.layout_class,
            "operation_signature": list(candidate.operation_signature),
            "source": source_name,
            "symbol": symbol,
        }
        if candidate.iteration_descriptor is not None:
            manifest_data["iteration_descriptor"] = (
                candidate.iteration_descriptor.to_data())
            manifest_data["iteration_descriptor_hash"] = (
                candidate.iteration_descriptor.stable_hash())
        manifest = json.dumps(
            manifest_data, ensure_ascii=True, indent=2, sort_keys=True) + "\n"
        return CArtifacts(
            symbol=symbol,
            declaration=declaration,
            header_name=header_name,
            source_name=source_name,
            header=header,
            source=source,
            manifest=manifest,
        )
