"""Emit deterministic C artifacts for loops and prepare-time execution plans."""
from pathlib import Path
import re
from .model import ExecutionLimits, ScalarLoop


def _macro(name, lines):
    return '#define ' + name + ' \\\n' + '\\\n'.join(line + ' ' for line in lines) + '\n'


def generate_loop_header(loops: tuple[ScalarLoop, ...], *, index_type: str, pair_fast_paths: bool = False) -> str:
    """Signed byte strides / multidimensional odometer, no broadcasting proof.

    The adapter supplies an ABI-compatible signed index type and scalar
    primitives. Pair, chunk, fixed-node and general signed-stride drivers share
    a single template. No separate hand-written production evaluator exists.
    """
    from .model import identifier
    identifier(index_type)
    if not loops or len({loop.name for loop in loops}) != len(loops):
        raise ValueError('empty or duplicate scalar loops')
    if pair_fast_paths:
        for loop in loops:
            by_name = {p.name: p.expression for p in loop.primitives}
            if any(by_name.get(name) != expression for name, expression in
                   (('ADD', 'left + right'), ('SUBTRACT', 'left - right'),
                    ('MULTIPLY', 'left * right'))):
                raise ValueError('pair paths require strict modular/float arithmetic')
    evaluators = []
    for loop in loops:
        for chunk in (False, True):
            access = '[lane]' if chunk else ''
            body = ['    do {', '        const CjKernelNode *node = &nodes[INDEX];']
            if not chunk:
                body += ['        TYPE left = slots[node->left];',
                         '        TYPE right = slots[node->right];']
            body += ['        switch (node->op) {']
            for primitive in loop.primitives:
                expression = primitive.expression
                if chunk:
                    expression = re.sub(r'\b(left|right)\b',
                        lambda match: f'slots[node->{match.group(0)}][lane]', expression)
                body += [f'        case CJ_OP_{primitive.name}:']
                if chunk:
                    body += ['            for (int lane = 0; lane < lanes; lane++)']
                body += [f'                slots[node->output]{access} = {expression};',
                         '            break;']
            body += ['        default: return 0;', '        }', '    } while (0)']
            name = f'CJ_EVAL_{loop.name}_{"CHUNK" if chunk else "NODE"}'
            evaluators.append(_macro(name + '(TYPE, NAME, INDEX)', body))
    body = ['    switch (node_count) {']
    for count in range(6, 1, -1):
        body += [f'    case {count}:']
        body += [f'        EVAL(TYPE, NAME, {i});' for i in range(count)]
        body += ['        break;']
    body += ['    default:', '        for (uint8_t node_index = 0; node_index < node_count; node_index++) {',
             '            EVAL(TYPE, NAME, node_index);', '        }', '        break;', '    }']
    evaluators.append(_macro('CJ_FIXED_NODES(EVAL, TYPE, NAME)', body))
    template = Path(__file__).with_name('loops.c.in').read_text()
    template = template.replace('@TRY_PAIR@', 'CJ_TRY_PAIR_FAST_PATH(TYPE);' if pair_fast_paths else '')
    template = template.replace('@EVALUATORS@', '\n'.join(evaluators))
    template = template.replace('@CHUNK_INSTANCES@', '\n'.join(
        f'DEFINE_CHUNK_KERNEL({loop.scalar.c_type}, {loop.name}, CJ_EVAL_{loop.name}_CHUNK)' for loop in loops))
    template = template.replace('@DRIVER_INSTANCES@', '\n'.join(
        f'DEFINE_KERNEL({loop.scalar.c_type}, {loop.name}, CJ_EVAL_{loop.name}_NODE)' for loop in loops))
    return ('/* Generated by crossjit-generator: do not edit. */\n'
            '#include "generated_crossjit_execution.h"\n'
            f'#define CJ_INDEX_TYPE {index_type}\n' + template + '\n#undef CJ_INDEX_TYPE\n')


def generate_execution_header(limits: ExecutionLimits, loops: tuple[ScalarLoop, ...]) -> str:
    primitives = {}
    for loop in loops:
        for primitive in loop.primitives:
            previous = primitives.setdefault(primitive.name, primitive.code)
            if previous != primitive.code:
                raise ValueError('primitive opcode conflicts across scalar contracts')
    if len(set(primitives.values())) != len(primitives):
        raise ValueError('primitive names share opcode')
    template = Path(__file__).with_name('plan.c.in').read_text()
    return (template.replace('@NODES@', str(limits.nodes)).replace('@INPUTS@', str(limits.inputs))
            .replace('@RANK@', str(limits.rank)).replace('@OPCODES@', '\n'.join(
                f'    CJ_OP_{name} = {code},' for name, code in sorted(primitives.items(), key=lambda p: p[1]))))


def generate_backend_header(*, index_type: str) -> str:
    """Generate raw-buffer handoff/traversal around a mature typed capability."""
    from .model import identifier
    identifier(index_type)
    return Path(__file__).with_name('backend.c.in').read_text().replace('@INDEX_TYPE@', index_type)
